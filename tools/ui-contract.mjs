// UI selector contract: every id, data-* attribute and class that the app's JS or the browser checks
// look up. A redesign may restyle and re-parent these freely; renaming one needs a matching change in
// the files listed next to it. Usage: node tools/ui-contract.mjs [--check]
//   (no flag) writes docs/ui-contract.txt
//   --check   fails if an id the JS or checks rely on is missing from public/index.html and is not
//             created by the JS itself
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const files = (dir, re) => readdirSync(join(root, dir)).filter((f) => re.test(f)).map((f) => join(dir, f));
const sources = [...files('public/js', /\.js$/), ...files('tools/browser-checks', /\.(c|m)?js$/)];
const html = readFileSync(join(root, 'public/index.html'), 'utf8');
const jsAll = files('public/js', /\.js$/).map((f) => readFileSync(join(root, f), 'utf8')).join('\n');

const found = new Map();                       // selector -> Set(files)
const add = (sel, file) => { if (!found.has(sel)) found.set(sel, new Set()); found.get(sel).add(file.replace(/^.*\//, '')); };
for (const f of sources) {
  const src = readFileSync(join(root, f), 'utf8');
  // selector strings inside quotes or template literals
  for (const m of src.matchAll(/['"`]([^'"`\n]*[#.[][^'"`\n]*)['"`]/g)) {
    for (const t of m[1].matchAll(/#([A-Za-z][\w-]*)/g)) add('#' + t[1], f);
    for (const t of m[1].matchAll(/\[(data-[\w-]+)/g)) add('[' + t[1] + ']', f);
    for (const t of m[1].matchAll(/(?:^|[\s>+~(,])\.([A-Za-z][\w-]*)/g)) add('.' + t[1], f);
    for (const t of m[1].matchAll(/^\.([A-Za-z][\w-]*)/g)) add('.' + t[1], f);
  }
  for (const m of src.matchAll(/getElementById\(['"]([\w-]+)['"]\)/g)) add('#' + m[1], f);
}

const sorted = [...found.entries()].sort(([a], [b]) => a.localeCompare(b));
if (process.argv.includes('--check')) {
  const missing = sorted.filter(([s]) => s.startsWith('#')).map(([s]) => s.slice(1))
    .filter((id) => !html.includes(`id="${id}"`) && !new RegExp(`id=\\\\?["']${id}\\\\?["']|id = ['"]${id}['"]|\\.id = ['"]${id}['"]|id="\\$\\{|id=\\\\"${id}`).test(jsAll) && !jsAll.includes(`id="${id}"`));
  if (missing.length) { console.log('ids used by JS/checks but not found in index.html or JS templates:\n  ' + missing.join('\n  ')); process.exit(1); }
  console.log(`contract ok: ${sorted.length} selectors`);
} else {
  const out = ['# UI selector contract (generated by tools/ui-contract.mjs; do not edit by hand)', '# selector  <-  files that use it', ''];
  for (const [s, fs] of sorted) out.push(`${s.padEnd(34)} <- ${[...fs].sort().join(', ')}`);
  writeFileSync(join(root, 'docs/ui-contract.txt'), out.join('\n') + '\n');
  console.log(`wrote docs/ui-contract.txt (${sorted.length} selectors)`);
}
